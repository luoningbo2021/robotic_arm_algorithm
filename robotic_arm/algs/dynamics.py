    def mass_matrix_new(self, theta: np.ndarray, load: np.ndarray = np.zeros(10)) -> np.ndarray:
        """通过逐关节逆动力学调用计算惯性矩阵.

        Args:
            theta: 关节角度, 形状为 (6,).
            load: 负载惯性参数, 形状为 (10,).
                顺序为 [XX, XY, XZ, YY, YZ, ZZ, MX, MY, MZ, M], 前六项为惯量分量, 接着三项为一阶质量矩, 最后一项为质量.

        Returns:
            惯性矩阵, 形状为 (6, 6).

            第 i 列为第 i 个关节加速度为 1, 其余关节加速度和所有关节速度均为 0 时的力矩.
        """
        mass_mat = np.zeros((6, 6))
        for i in range(6):
            ddtheta = np.zeros(6)
            ddtheta[i] = 1
            mass_mat[:, i] = self.inverse_dynamics(theta, np.zeros(6), ddtheta, gravity=np.zeros(3))
        return mass_mat
    
    def forward_dynamics(self, theta: np.ndarray, dtheta: np.ndarray, tau: np.ndarray, f_tip: np.ndarray = np.zeros(6), gravity: np.ndarray = np.array([0, 0, -9.8]), load: np.ndarray = np.zeros(10)) -> np.ndarray:
        """计算正动力学.

        Args:
            theta: 关节角度, 形状为 (6,).
            dtheta: 关节速度, 形状为 (6,).
            tau: 关节力矩, 形状为 (6,).
            f_tip: 末端坐标系下的外力和外力矩, 形状为 (6,)
            gravity: 基坐标系下的重力加速度, 形状为 (3,), 顺序为 [gx, gy, gz].
            load: 末端负载惯性参数, 形状为 (10,).
                顺序为 [XX, XY, XZ, YY, YZ, ZZ, MX, MY, MZ, M], 前六项为惯量分量, 接着三项为一阶质量矩, 最后一项为质量.

        Returns:
            关节加速度, 形状为 (6,).
        """
        CCG = self.inverse_dynamics(theta, dtheta, np.zeros(6), f_tip, gravity, load)
        ddtheta = np.dot(np.linalg.inv(self.mass_matrix(theta), load), tau-CCG)
        return ddtheta

